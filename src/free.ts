type SizeOption =
	| 'xs' | 'sm' | 'lg'
	| '1x' | '2x' | '3x' | '4x' | '5x'
	| '6x' | '7x' | '8x' | '9x' | '10x'

type PullOption = 'left' | 'right'
type AnimationOption = 'spin' | 'pulse'
type RotateOption = '90' | '180' | '270'
type FlipOption = 'horizontal' | 'vertical' | 'both'

type IconProps = {
	icon: string
	size?: SizeOption
	fixedWidth?: boolean
	animation?: AnimationOption
	rotate?: RotateOption
	flip?: FlipOption
	pull?: PullOption
	border?: boolean
	inverse?: boolean
	stack?: '1x' | '2x'
	className?: string
	style?: CSSProperties
	title?: string
	'aria-hidden'?: boolean
	'aria-label'?: string
}

export function FontAwesomeIcon({
	icon,
	size,
	fixedWidth,
	animation,
	rotate,
	flip,
	pull,
	border,
	inverse,
	stack,
	className,
	...rest
}: IconProps) {
	if (!icon) return null
	const classes = [
		icon,
		size && `fa-${size}`,
		fixedWidth && 'fa-fw',
		animation && `fa-${animation}`,
		rotate && `fa-rotate-${rotate}`,
		flip && `fa-flip-${flip}`,
		pull && `fa-pull-${pull}`,
		border && 'fa-border',
		inverse && 'fa-inverse',
		stack && `fa-stack-${stack}`,
		className,
	].filter(Boolean).join(' ')
	return createElement('i', {
		className: classes,
		...rest,
	})
}
